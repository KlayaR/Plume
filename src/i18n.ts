export function translate(lang: UiLang, text: string, vars?: Record<string, string | number>): string {
  let s = lang === 'fr' ? FR[text] ?? text : text
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

